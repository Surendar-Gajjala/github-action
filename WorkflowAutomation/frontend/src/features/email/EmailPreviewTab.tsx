import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useEffect, useState } from 'react';
import { employeesApi, queryKeys } from '../../api/employees';
import type { EmailPreview } from '../../api/types';
import { StatusBadge } from '../../components/StatusBadge';
import { Button, Card, EmptyState, ErrorMessage, Field, SelectEmployeeHint } from '../../components/ui';
import { formatDateTime } from '../../lib/format';
import { POLL_INTERVAL_MS, useWorkflowActive } from '../workflow/useWorkflow';

const SOURCE_LABEL = { AI: 'Generated by AI', FALLBACK: 'Fallback template (AI unavailable)', EDITED: 'Edited by HR' };

export function EmailPreviewTab({ employeeId }: { employeeId: number | null }) {
  const active = useWorkflowActive(employeeId);
  const email = useQuery({
    queryKey: queryKeys.email(employeeId ?? 0),
    queryFn: () => employeesApi.emailPreview(employeeId!),
    enabled: employeeId != null,
    refetchInterval: active ? POLL_INTERVAL_MS : false,
  });

  if (employeeId == null) return <SelectEmployeeHint />;
  if (email.isPending) return <Card>Loading email…</Card>;
  if (email.isError) return <ErrorMessage error={email.error} />;
  if (!email.data.available) {
    return <EmptyState>The welcome email has not been generated yet. It appears here once the AI step completes.</EmptyState>;
  }
  return <EmailView employeeId={employeeId} email={email.data} />;
}

function EmailView({ employeeId, email }: { employeeId: number; email: EmailPreview }) {
  const queryClient = useQueryClient();
  const [subject, setSubject] = useState(email.subject ?? '');
  const [body, setBody] = useState(email.body ?? '');

  useEffect(() => {
    setSubject(email.subject ?? '');
    setBody(email.body ?? '');
  }, [email.subject, email.body]);

  const approve = useMutation({
    mutationFn: () =>
      employeesApi.approveEmail(employeeId, {
        subject: subject !== email.subject ? subject : undefined,
        body: body !== email.body ? body : undefined,
      }),
    onSuccess: (data) => {
      queryClient.setQueryData(queryKeys.email(employeeId), data);
      queryClient.invalidateQueries({ queryKey: queryKeys.workflow(employeeId) });
      queryClient.invalidateQueries({ queryKey: ['employees'] });
    },
  });

  const editable = email.awaitingApproval;
  const subjectInvalid = subject.trim().length === 0 || /[\r\n]/.test(subject) || subject.length > 200;
  const bodyInvalid = body.trim().length === 0 || body.length > 8000;

  return (
    <div className="grid gap-6 lg:grid-cols-3">
      <div className="lg:col-span-2">
        <Card title="Welcome email" actions={<StatusBadge status={email.status} />}>
          {editable && (
            <div className="mb-4 rounded-md border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-900">
              Approval is required. Review and edit the email if needed, then approve it to send.
            </div>
          )}
          <dl className="mb-5 grid gap-4 sm:grid-cols-2">
            <Field label="Recipient" value={email.recipient} />
            <Field label="Content" value={email.contentSource ? SOURCE_LABEL[email.contentSource] : '—'} />
            {email.sentAt && <Field label="Sent at" value={formatDateTime(email.sentAt)} />}
          </dl>

          <label htmlFor="email-subject" className="mb-1 block text-xs font-medium uppercase tracking-wide text-slate-500">
            Subject
          </label>
          {editable ? (
            <input
              id="email-subject"
              className={`input mb-4 ${subjectInvalid ? 'input-error' : ''}`}
              value={subject}
              maxLength={200}
              onChange={(e) => setSubject(e.target.value)}
            />
          ) : (
            <p id="email-subject" className="mb-4 text-sm font-medium text-slate-900">
              {email.subject}
            </p>
          )}

          <label htmlFor="email-body" className="mb-1 block text-xs font-medium uppercase tracking-wide text-slate-500">
            Email body
          </label>
          {editable ? (
            <textarea
              id="email-body"
              rows={14}
              className={`input font-mono ${bodyInvalid ? 'input-error' : ''}`}
              value={body}
              maxLength={8000}
              onChange={(e) => setBody(e.target.value)}
            />
          ) : (
            <div id="email-body" className="whitespace-pre-wrap rounded-md bg-slate-50 p-4 text-sm leading-relaxed text-slate-800">
              {email.body}
            </div>
          )}

          {editable && (
            <div className="mt-4 flex flex-wrap items-center gap-3">
              <Button onClick={() => approve.mutate()} disabled={approve.isPending || subjectInvalid || bodyInvalid}>
                {approve.isPending ? 'Approving…' : 'Approve & Send'}
              </Button>
              <Button
                variant="secondary"
                onClick={() => {
                  setSubject(email.subject ?? '');
                  setBody(email.body ?? '');
                }}
              >
                Discard edits
              </Button>
            </div>
          )}
          {approve.isError && (
            <div className="mt-3">
              <ErrorMessage error={approve.error} />
            </div>
          )}
        </Card>
      </div>

      <Card title="Onboarding checklist">
        <ul className="space-y-2 text-sm text-slate-700">
          {email.checklist.map((item) => (
            <li key={item} className="flex gap-2">
              <span aria-hidden="true" className="mt-0.5 h-4 w-4 shrink-0 rounded border border-slate-300" />
              {item}
            </li>
          ))}
        </ul>
      </Card>
    </div>
  );
}

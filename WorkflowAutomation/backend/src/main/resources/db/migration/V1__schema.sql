-- Employee onboarding schema.
-- Written in portable SQL so it runs on both PostgreSQL and H2 (MODE=PostgreSQL).

CREATE SEQUENCE employee_number_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE employees (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number   VARCHAR(20)  NOT NULL,
    first_name        VARCHAR(100) NOT NULL,
    last_name         VARCHAR(100) NOT NULL,
    email             VARCHAR(254) NOT NULL,
    job_title         VARCHAR(150) NOT NULL,
    department        VARCHAR(100) NOT NULL,
    joining_date      DATE         NOT NULL,
    reporting_manager VARCHAR(150) NOT NULL,
    github_username   VARCHAR(39)  NOT NULL,
    github_repository VARCHAR(200) NOT NULL,
    access_level      VARCHAR(20)  NOT NULL,
    idempotency_key   VARCHAR(100),
    created_by        VARCHAR(100) NOT NULL,
    updated_by        VARCHAR(100) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_employees_employee_number UNIQUE (employee_number),
    CONSTRAINT uk_employees_email UNIQUE (email),
    CONSTRAINT uk_employees_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_employees_access_level CHECK (access_level IN ('READ', 'TRIAGE', 'WRITE', 'MAINTAIN', 'ADMIN'))
);

CREATE INDEX ix_employees_created_at ON employees (created_at);
CREATE INDEX ix_employees_department ON employees (department);
CREATE INDEX ix_employees_last_name ON employees (last_name);

CREATE TABLE onboarding_workflows (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id             BIGINT       NOT NULL,
    overall_status          VARCHAR(30)  NOT NULL,
    current_step            VARCHAR(40),
    email_approval_required BOOLEAN      NOT NULL DEFAULT FALSE,
    started_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at            TIMESTAMP WITH TIME ZONE,
    last_error              VARCHAR(2000),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_workflows_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT uk_workflows_employee UNIQUE (employee_id),
    CONSTRAINT ck_workflows_status CHECK (overall_status IN ('IN_PROGRESS', 'AWAITING_APPROVAL', 'COMPLETED', 'FAILED'))
);

CREATE INDEX ix_workflows_status ON onboarding_workflows (overall_status);

CREATE TABLE workflow_steps (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id        BIGINT       NOT NULL,
    step_name          VARCHAR(40)  NOT NULL,
    step_order         INTEGER      NOT NULL,
    status             VARCHAR(30)  NOT NULL,
    attempts           INTEGER      NOT NULL DEFAULT 0,
    started_at         TIMESTAMP WITH TIME ZONE,
    completed_at       TIMESTAMP WITH TIME ZONE,
    error_message      VARCHAR(2000),
    external_reference VARCHAR(500),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_steps_workflow FOREIGN KEY (workflow_id) REFERENCES onboarding_workflows (id),
    CONSTRAINT uk_steps_workflow_step UNIQUE (workflow_id, step_name),
    CONSTRAINT ck_steps_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'SUCCESS', 'FAILED', 'FAILED_UNCERTAIN', 'AWAITING_APPROVAL', 'SKIPPED'))
);

CREATE INDEX ix_steps_status ON workflow_steps (status);
CREATE INDEX ix_steps_workflow_order ON workflow_steps (workflow_id, step_order);

CREATE TABLE onboarding_artifacts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id   BIGINT       NOT NULL,
    artifact_type VARCHAR(30)  NOT NULL,
    recipient     VARCHAR(254),
    subject       VARCHAR(300),
    content       VARCHAR(20000),
    metadata      VARCHAR(10000),
    content_source VARCHAR(20),
    external_url  VARCHAR(500),
    external_id   VARCHAR(100),
    status        VARCHAR(30)  NOT NULL,
    sent_at       TIMESTAMP WITH TIME ZONE,
    created_by    VARCHAR(100) NOT NULL,
    updated_by    VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_artifacts_workflow FOREIGN KEY (workflow_id) REFERENCES onboarding_workflows (id),
    CONSTRAINT uk_artifacts_workflow_type UNIQUE (workflow_id, artifact_type),
    CONSTRAINT ck_artifacts_type CHECK (artifact_type IN ('WELCOME_EMAIL', 'GITHUB_ISSUE')),
    CONSTRAINT ck_artifacts_status CHECK (status IN ('DRAFT', 'APPROVED', 'SENDING', 'SENT', 'SEND_FAILED', 'CREATED', 'FAILED'))
);

CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(100) NOT NULL,
    action         VARCHAR(50)  NOT NULL,
    entity_type    VARCHAR(50)  NOT NULL,
    entity_id      BIGINT,
    details        VARCHAR(2000),
    correlation_id VARCHAR(64),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_audit_entity ON audit_events (entity_type, entity_id);
CREATE INDEX ix_audit_created_at ON audit_events (created_at);
